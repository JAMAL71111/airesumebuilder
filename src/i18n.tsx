const dicts: Record<Lang, Dict> = { en, ar };

interface LangCtx {
  lang: Lang;
  dir: 'ltr' | 'rtl';
  isRTL: boolean;
  setLang: (l: Lang) => void;
  toggle: () => void;
  t: (key: string) => string;
}

const LanguageContext = createContext<LangCtx | undefined>(undefined);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    if (typeof window === 'undefined') return 'en';
    return (localStorage.getItem('resumate-lang') as Lang | null) || 'en';
  });

  const dir = lang === 'ar' ? 'rtl' : 'ltr';
  const isRTL = dir === 'rtl';

  useEffect(() => {
    const root = document.documentElement;
    root.lang = lang;
    root.dir = dir;
    localStorage.setItem('resumate-lang', lang);
  }, [lang, dir]);

  const t = (key: string) => dicts[lang][key] ?? key;

  return (
    <LanguageContext.Provider
      value={{
        lang,
        dir,
        isRTL,
        setLang: setLangState,
        toggle: () => setLangState((l) => (l === 'en' ? 'ar' : 'en')),
        t,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
}

export function useLang() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useLang must be used within LanguageProvider');
  return ctx;
}
